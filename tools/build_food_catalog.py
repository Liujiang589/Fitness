def main():
    source = Path(sys.argv[1])
    root = Path(__file__).resolve().parents[1]
    def rows(name):
        with (source / name).open(encoding="utf-8-sig", newline="") as handle:
            return list(csv.DictReader(handle))
    foods = {int(row["fdc_id"]): row for row in rows("food.csv")}
    selected_ids = {str(row[0]) for row in SELECTION}
    nutrients = {}
    for row in rows("food_nutrient.csv"):
        if row["fdc_id"] in selected_ids and row["nutrient_id"] in {"1003", "1004", "1005"}:
            nutrients.setdefault(int(row["fdc_id"]), {})[row["nutrient_id"]] = float(row["amount"])
    records = []
    code = ["package app.duolian.local.domain", "", "// Generated by tools/build_food_catalog.py from USDA SR Legacy, April 2018.",
            "// Curated Chinese names describe the original food and its preparation; no guessed nutrient values.",
            "object FoodCatalog {", "    val all: List<FoodSpec> = listOf("]
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    for identifier, name, preparation, category, aliases in SELECTION:
        values = nutrients[identifier]
        assert set(values) == {"1003", "1004", "1005"}, identifier
        protein, fat, carbs = values["1003"], values["1004"], values["1005"]
        url = f"https://fdc.nal.usda.gov/food-details/{identifier}/nutrients"
        record = dict(fdcId=identifier, name=name, preparation=preparation, category=category,
                      originalDescription=foods[identifier]["description"], proteinPer100g=protein,
                      carbsPer100g=carbs, fatPer100g=fat, sourceUrl=url)
        records.append(record)
        args = [quote(f"usda_{identifier}"), quote(name), quote(preparation), quote(category),
                str(protein), str(carbs), str(fat), quote(f"USDA SR Legacy · FDC {identifier}"), quote(url), quote(aliases)]
        code.append("        FoodSpec(" + ", ".join(args) + "),")
    code += ["    )", "}", ""]
    target = root / "android/app/src/main/java/app/duolian/local/domain/FoodCatalog.kt"
    target.write_bytes("\n".join(code).encode("utf-8"))
    snapshot = root / "docs/nutrition/usda-sr-legacy-selection.json"
    snapshot.parent.mkdir(parents=True, exist_ok=True)
    snapshot.write_bytes((json.dumps(dict(dataset="USDA SR Legacy April 2018", unit="g per 100 g edible portion",
        archive="https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip",
        nutrients={"1003": "Protein", "1004": "Total lipid (fat)", "1005": "Carbohydrate, by difference"},
        foods=records), ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
    print(f"Generated {len(records)} traced food records: {target}")


if __name__ == "__main__":
    main()
