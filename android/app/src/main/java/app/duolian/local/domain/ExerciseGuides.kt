package app.duolian.local.domain

enum class MotionKind {
    BENCH, SQUAT, PULLDOWN, SEATED_ROW, SHOULDER_PRESS, CURL, BODY_SQUAT, PUSHUP,
    INCLINE_BENCH, DB_BENCH, FLY, CABLE_FLY, ROW, ONE_ARM_ROW, PULLUP, STRAIGHT_PULLDOWN,
    DB_DEADLIFT, RDL, LEG_PRESS, SPLIT_SQUAT, LEG_EXTENSION, LEG_CURL, BRIDGE,
    LATERAL_RAISE, FRONT_RAISE, REVERSE_FLY, FACE_PULL, ARNOLD, HAMMER_CURL, BARBELL_CURL,
    CABLE_CURL, PUSHDOWN, OVERHEAD_TRICEPS, LYING_TRICEPS, CRUNCH, HANGING_RAISE,
    REVERSE_CRUNCH, TWIST, STANDING_CALF, SEATED_CALF
}

data class ExerciseGuide(val kind: MotionKind, val name: String, val muscle: String,
    val equipment: String, val focus: String, val stages: List<String>,
    val breathing: String, val mistakes: List<String>) {
    val key get() = kind.name.lowercase(java.util.Locale.ROOT)
    val highlightedRegions get() = when(kind) {
        MotionKind.DB_DEADLIFT,MotionKind.RDL -> setOf("腿部","背部")
        else -> setOf(muscle)
    }
    val phaseNames get() = when(kind) {
        MotionKind.SQUAT,MotionKind.BODY_SQUAT,MotionKind.SPLIT_SQUAT -> listOf("站稳准备","控制下蹲","伸髋站起")
        MotionKind.RDL,MotionKind.DB_DEADLIFT -> listOf("站立准备","屈髋下放","伸髋站起")
        MotionKind.FLY -> listOf("胸前准备","控制打开","弧线合拢")
        MotionKind.CABLE_FLY -> listOf("打开准备","胸前合拢","控制打开")
        MotionKind.PUSHUP -> listOf("稳定支撑","屈肘下落","推起还原")
        MotionKind.PULLUP -> listOf("稳定悬垂","屈肘上拉","缓慢下落")
        MotionKind.HANGING_RAISE -> listOf("稳定悬垂","控制举腿","缓慢放回")
        MotionKind.CRUNCH -> listOf("仰卧准备","卷起上背","缓慢放回")
        MotionKind.REVERSE_CRUNCH -> listOf("屈膝准备","卷起骨盆","缓慢放回")
        MotionKind.BRIDGE -> listOf("仰卧准备","控制抬髋","缓慢放回")
        MotionKind.PULLDOWN -> listOf("向上伸臂","向下拉回","伸臂回程")
        else -> listOf("起始姿势", "发力过程", "控制还原")
    }
}

